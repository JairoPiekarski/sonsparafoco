class SoundModel {
  final String id;
  final String title;
  final String icon;
  final String path;
  final String category;
  final bool isPremium;
  final String source;

  SoundModel({
    required this.id,
    required this.title,
    required this.icon,
    required this.path,
    required this.category,
    required this.isPremium,
    required this.source
  });
}
